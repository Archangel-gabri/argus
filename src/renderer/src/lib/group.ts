/**
 * Раскладка списка по видам в заданном порядке.
 *
 * Одна и та же операция встречалась дважды — для ИИ-доступов и для финансовых
 * счетов — двумя копиями с разными типами. Разница между ними была только в
 * том, откуда берётся вид и в каком порядке идут группы; всё остальное
 * совпадало посимвольно.
 *
 * Пустые группы отбрасываются: пустая полка на экране — это шум, а не
 * информация о том, что такой вид существует.
 */
export function groupInOrder<T, K>(
  items: readonly T[],
  order: readonly K[],
  kindOf: (item: T) => K
): Array<{ kind: K; items: T[] }> {
  return order
    .map((kind) => ({ kind, items: items.filter((item) => kindOf(item) === kind) }))
    .filter((group) => group.items.length > 0)
}
