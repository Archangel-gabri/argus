// Форматирование денег обслуживает и точные банковские остатки, и приблизительные сводки.
// Оба прежних правила оказались неверны, и оба — молча: одно теряло знак после запятой
// («$5,778.2»), другое округляло остаток 1000,49 до «$1 000», то есть показывало другую сумму.
import { describe, expect, it } from 'vitest'
import { money, approxMoney, plural, tokens } from './format'

// Разряды Intl разделяет НЕРАЗРЫВНЫМ пробелом, и его вид зависит от версии ICU в движке.
// Сравнивать посимвольно — значит привязать тест к сборке Node, а не к поведению приложения.
const norm = (s: string): string => s.replace(/[\u00a0\u202f\s]/g, ' ')
const shows = (actual: string, expected: string): void => expect(norm(actual)).toBe(expected)

describe('money', () => {
  it('копейки показываются, когда они есть, и не показываются, когда их нет', () => {
    shows(money(1000.49), '$1 000,49')
    shows(money(1999.5, 'RUB'), '1 999,50 ₽')
    shows(money(5778.2), '$5 778,20')
    shows(money(125_000, 'RUB'), '125 000 ₽')
    shows(money(4), '$4')
  })

  it('сумма меньше копейки — это не ноль', () => {
    // Помодельная строка расхода ИИ: доли цента за короткий ответ. «$0» читается как
    // «бесплатно», хотя деньги потрачены.
    shows(money(0.004), '<$0,01')
    shows(money(0), '$0')
  })

  it('разряды разделяются по-русски', () => {
    // «125,000 ₽» в рублях читается как дробная часть.
    expect(money(125_000, 'RUB')).not.toContain(',000')
  })
})

describe('approxMoney', () => {
  it('помечает сумму приблизительной, когда была конвертация', () => {
    shows(approxMoney(100, ['RUB']), '≈ $100')
    shows(approxMoney(100, ['EUR', 'USD']), '≈ $100')
  })

  it('без конвертации знак не ставится', () => {
    shows(approxMoney(100.5, ['USD']), '$100,50')
    shows(approxMoney(100, []), '$100')
  })
})

describe('plural', () => {
  it('склоняет по русским правилам', () => {
    const форма = (n: number): string => `${n} ${plural(n, 'устройство', 'устройства', 'устройств')}`
    expect(форма(1)).toBe('1 устройство')
    expect(форма(2)).toBe('2 устройства')
    expect(форма(5)).toBe('5 устройств')
    expect(форма(11)).toBe('11 устройств')
    expect(форма(21)).toBe('21 устройство')
    expect(форма(0)).toBe('0 устройств')
  })
})

describe('tokens', () => {
  it('сокращает по-русски', () => {
    expect(tokens(4_900_000)).toBe('4.9 млн')
    expect(tokens(20_000)).toBe('20 тыс.')
    expect(tokens(999)).toBe('999')
  })
})

describe('approxMoney на маленьких суммах', () => {
  it('не превращает настоящие деньги в «$0»', () => {
    // Рублёвый остаток 30 ₽ ≈ $0.38. Внешнее округление до целого доллара делало из него «$0»,
    // то есть «денег нет» — на главной плитке экрана финансов у владельца с рублёвыми счетами.
    expect(approxMoney(0.38, ['RUB'])).not.toMatch(/^≈ \$0$/)
    // Годовая подписка 300 ₽ — это $0.32 в месяц, а не «бесплатно».
    expect(approxMoney(0.32, ['RUB'])).not.toMatch(/^≈ \$0$/)
  })

  it('настоящий ноль остаётся нулём', () => {
    expect(approxMoney(0, ['RUB'])).toBe('≈ $0')
  })

  it('крупные суммы по-прежнему без копеек — они шум при приблизительном курсе', () => {
    expect(approxMoney(228.47, ['RUB'])).toBe('≈ $228')
  })
})
