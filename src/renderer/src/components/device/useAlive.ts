import { useEffect, useRef, type RefObject } from 'react'

/**
 * «Этот блок ещё на экране?» — спрашивают перед тем, как показать пришедший ответ.
 *
 * Ответ, начатый для устройства A, не имеет права трогать открытое следом устройство B: гео
 * подставило бы чужую страну, проба — чужую ОС, а «сохранено» закрыло бы не тот диалог.
 * Раньше ту же роль играл счётчик поколений, который приходилось сверять вручную в каждой
 * async-функции; теперь ответ на вопрос даёт сам React — вместе с уходом блока с экрана.
 *
 * Значение выставляется на КАЖДОМ монтировании, а не один раз при создании ref: в StrictMode
 * первый проход сразу размонтируется, и однократной инициализации хватило бы ровно до него.
 */
export function useAlive(): RefObject<boolean> {
  const alive = useRef(true)
  useEffect(() => {
    alive.current = true
    return () => {
      alive.current = false
    }
  }, [])
  return alive
}
