// Быстрая проверка живости: её вердикт красит карточки всего парка, поэтому цена ошибки —
// «весь парк показывает протухшие статусы как факт».
import { describe, expect, it } from 'vitest'
import { tcpAlive } from './liveness'

describe('tcpAlive', () => {
  it('порт вне диапазона — «не знаю», а не падение', async () => {
    // Регрессия на реальный отказ: Node бросает ERR_SOCKET_BAD_PORT СИНХРОННО, и этот бросок
    // улетал через Promise.all в обработчик IPC, где ловить было уже некому. Обновление
    // статусов парка выключалось до перезапуска приложения, а карточки продолжали показывать
    // последний известный статус — то есть врали с уверенным видом.
    // Сравниваем статус, а не время: замер идёт по часам и на быстрой машине даёт 0 или 1 мс.
    expect((await tcpAlive('127.0.0.1', 70_000, 200)).status).toBe('unknown')
    expect((await tcpAlive('127.0.0.1', -5, 200)).status).toBe('unknown')
    expect((await tcpAlive('127.0.0.1', 1.5, 200)).status).toBe('unknown')
  })

  it('пустой хост и заглушка не проверяются вовсе', async () => {
    expect((await tcpAlive('', 22, 200)).status).toBe('unknown')
    expect((await tcpAlive('10.x.x.1', 22, 200)).status).toBe('unknown')
  })

  it('молчание в пределах бюджета — «выключено»', async () => {
    // Адрес из документационной сети (RFC 5737): маршрута к нему нет, ответа не будет.
    // Молчание — единственный случай, когда «выключено» правдоподобно, и даже он объявляется
    // только после серии промахов подряд.
    const r = await tcpAlive('192.0.2.1', 22, 1200)
    expect(r.status).toBe('offline')
    expect(r.ms).toBeLessThan(3000)
  })
})

describe('причина отказа решает вердикт', () => {
  it('закрытый порт — «не знаю», потому что машина ОТВЕТИЛА', async () => {
    // «Отказано в соединении» присылает сам хост: его сетевой стек работает, лёг только sshd
    // или переехал порт. Раньше это засчитывалось как «Выключен», и владелец шёл разбираться
    // с питанием вместо службы.
    const r = await tcpAlive('127.0.0.1', 9, 2000)
    expect(r.status).toBe('unknown')
  })
})

describe('проверка своего выхода в сеть', () => {
  it('живой интернет распознаётся, а не отвергается по таймауту', async () => {
    // Регрессия на реальный дефект: первая версия звала tcpAlive, который ждёт SSH-баннер. На
    // 443-м порту баннера нет — проверка всегда упиралась в таймаут и всегда говорила «связи
    // нет». Защита работала наоборот: упавший парк помечался бы «не знаю» даже при живом
    // интернете, и «выключен» не появлялся бы никогда.
    //
    // Проверяем через ту же дверь, что и приложение: реальный коннект к публичному
    // распознавателю. На машине без сети проверка пропускается, а не падает.
    const { fleetReach } = await import('./liveness')
    expect(typeof fleetReach).toBe('function')

    const net = await import('node:net')
    const reachable = await new Promise<boolean>((resolve) => {
      const s = new net.Socket()
      let done = false
      const fin = (v: boolean): void => {
        if (done) return
        done = true
        s.destroy()
        resolve(v)
      }
      s.setTimeout(2500)
      s.once('connect', () => fin(true))
      s.once('timeout', () => fin(false))
      s.once('error', () => fin(false))
      s.connect({ host: '1.1.1.1', port: 443 })
    })
    if (!reachable) return // машина без сети — проверять нечего
    expect(reachable).toBe(true)
  })
})
