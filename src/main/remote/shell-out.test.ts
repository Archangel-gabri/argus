// Разбор ответа зонда и экранирование для оболочки. Обе вещи жили копиями (три и две
// соответственно) и обе тихо расходились. Цена расхождения разная: у разборщика — пустые поля
// на карточке, у экранирования — команда, выполненная на чужой машине не так, как задумано.
import { describe, expect, it } from 'vitest'
import { quoteForShell, sections } from './shell-out'

describe('разбор блоков по маркерам', () => {
  it('раскладывает вывод одной команды на блоки', () => {
    // Одна команда возвращает несколько блоков намеренно: каждый лишний вызов — отдельное
    // SSH-рукопожатие.
    const out = '@@mem\n16384 8192\n@@disk\n/ 45%\n/home 12%\n'
    expect(sections(out)).toEqual({ mem: ['16384 8192'], disk: ['/ 45%', '/home 12%'] })
  })

  it('выбрасывает то, что печатает сама оболочка до первого маркера', () => {
    // Баннер входа и «You have mail» не относятся ни к одному блоку.
    const out = 'Last login: Tue\nYou have mail.\n@@cpu\n12\n'
    expect(sections(out)).toEqual({ cpu: ['12'] })
  })

  it('пустой блок остаётся пустым, а не исчезает', () => {
    // Разница между «спросили и пусто» и «не спрашивали» здесь такая же, как везде в парке.
    expect(sections('@@ports\n@@mem\n8\n')).toEqual({ ports: [], mem: ['8'] })
  })
})

describe('экранирование для оболочки', () => {
  it('оборачивает значение в одинарные кавычки', () => {
    expect(quoteForShell('обычно')).toBe("'обычно'")
  })

  it('обезвреживает кавычку внутри значения', () => {
    // Без этого значение закрыло бы строку и остаток уехал бы в команду как код.
    expect(quoteForShell("сес'сия")).toBe("'сес'\\''сия'")
  })

  it('пробелы и точки с запятой остаются данными, а не командой', () => {
    expect(quoteForShell('rm -rf /; echo')).toBe("'rm -rf /; echo'")
  })
})
