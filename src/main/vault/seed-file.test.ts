// Файл засева искали рядом с кодом и в рабочем каталоге. В собранный AppImage эти файлы не
// входят, а рабочий каталог у него домашний — то есть установленное приложение засев не
// выполняло вовсе. Незаметно это было потому, что данные, засеянные раньше при разработке,
// уже лежали в хранилище и выглядели как доказательство работоспособности.
import { describe, expect, it } from 'vitest'
import { seedDirs } from './seed-file'

describe('где ищется файл засева', () => {
  it('каталог данных приложения идёт первым', () => {
    // Единственное место, одинаково доступное и установленной копии, и запущенной из исходников.
    expect(seedDirs({ userData: '/data', appPath: '/app', cwd: '/cwd' })).toEqual(['/data', '/app', '/cwd'])
  })

  it('без Electron остаётся рабочий каталог — тесты и скрипты тоже должны находить файл', () => {
    expect(seedDirs({ cwd: '/cwd' })).toEqual(['/cwd'])
  })

  it('рабочий каталог не теряется никогда', () => {
    for (const dirs of [seedDirs({ userData: '/d', cwd: '/c' }), seedDirs({ appPath: '/a', cwd: '/c' })]) {
      expect(dirs).toContain('/c')
    }
  })
})
