/**
 * Добавление колонки при миграции схемы хранилища.
 *
 * Схема наращивается через `ALTER TABLE … ADD COLUMN`, и на уже обновлённой базе такой запрос
 * закономерно падает — колонка есть. Раньше это лечилось голым `catch {}` вокруг каждого из
 * одиннадцати запросов, с комментарием «column already exists».
 *
 * Беда в том, что это предположение, а не проверка. SQLite отдаёт `SQLITE_ERROR` и на дубль
 * колонки, и на «нет такой таблицы», и на нехватку места, и на ошибку ввода-вывода — различает
 * их только текст сообщения. То есть повреждение базы или кончившийся диск проглатывались
 * молча, и приложение продолжало работать на схеме, которой нет. Такую поломку человек увидел
 * бы позже и в другом месте, где её уже не связать с причиной.
 *
 * Здесь ожидаемая ошибка называется по имени, а всё остальное летит наверх.
 */
export function isDuplicateColumnError(e: unknown): boolean {
  // Бросить в JS можно что угодно. Объект без toString дал бы «[object Object]», и признак
  // «колонка уже есть» перестал бы находиться — то есть миграция падала бы на ровном месте.
  const msg =
    e instanceof Error
      ? e.message
      : typeof e === 'string'
        ? e
        : e && typeof e === 'object' && 'message' in e
          ? String((e as { message: unknown }).message)
          : ''
  return /duplicate column name/i.test(msg)
}

/** Выполнить ALTER, стерпев ТОЛЬКО «колонка уже есть». Возвращает true, если колонку добавили. */
export function addColumn(exec: (sql: string) => void, sql: string): boolean {
  try {
    exec(sql)
    return true
  } catch (e) {
    if (isDuplicateColumnError(e)) return false
    // Диск кончился, база повреждена, таблицы нет — это не «уже мигрировано».
    throw new Error(`миграция схемы не удалась (${sql}): ${(e as Error).message}`, { cause: e })
  }
}
