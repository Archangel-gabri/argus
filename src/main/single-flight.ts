/**
 * Склейка одновременных одинаковых запросов.
 *
 * Пока карточка устройства открыта, по нему одновременно работают три независимых опроса:
 * обновление карточки, вкладка «Метрики» и определение запущенной ОС. Каждый лезет по SSH,
 * и на двухзагрузочном ПК каждый может ждать до девяти секунд — запросы начинали наслаиваться
 * друг на друга, а SSH-подключения плодиться.
 *
 * Договориться между собой они не могут: это разные части интерфейса, и каждая имеет право
 * спросить. Поэтому склейка живёт здесь, где виден весь поток: пока ответ на такой же вопрос
 * ещё готовится, второй спрашивающий получает ТОТ ЖЕ ответ, а не заводит вторую работу.
 *
 * Это именно склейка, а не кэш: ничего не хранится дольше самого запроса. Спросили после
 * ответа — работа выполнится заново, и данные будут свежими.
 */
const inFlight = new Map<string, Promise<unknown>>()

export function singleFlight<T>(key: string, fn: () => Promise<T>): Promise<T> {
  const existing = inFlight.get(key) as Promise<T> | undefined
  if (existing) return existing
  const p = (async () => {
    try {
      return await fn()
    } finally {
      inFlight.delete(key)
    }
  })()
  inFlight.set(key, p)
  return p
}

/** Сколько работ выполняется прямо сейчас — для диагностики. */
export const inFlightCount = (): number => inFlight.size

/**
 * Забыть все текущие склейки. Зовётся при блокировке приложения.
 *
 * Сама работа этим не отменяется — промис доживёт своё, — но новый спрашивающий после
 * разблокировки получит СВЕЖИЙ ответ, а не тот, что начали собирать в прошлой сессии, до
 * возможной правки устройства или смены доступов.
 */
export function clearInFlight(): void {
  inFlight.clear()
}
