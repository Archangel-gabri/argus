// Разбор вывода удалённых команд и подготовка аргументов для оболочки.
//
// Обе вещи лежат здесь, потому что обе были размножены копипастой и обе тихо расходятся.
//
// `sections` — разбор ответа зонда, размеченного маркерами `@@имя`. Одна команда возвращает
// сразу несколько блоков (память, диски, сеть), потому что каждый лишний вызов — это отдельное
// SSH-рукопожатие. Разборщик существовал тремя копиями: в `metrics.ts`, `metrics-bsd.ts` и
// `hardware.ts`, причём третья уже успела разойтись по форме записи. Пока копий три, правка
// формата маркера в одной из них молча ломает две остальные — и заметно это только по пустым
// полям на карточке.
//
// `quoteForShell` — экранирование значения одинарными кавычками. Копий было две (`session.ts` и
// `pc.ts` под разными именами). Цена расхождения выше, чем у разборщика: значение попадает в
// командную строку на чужой машине, и ошибка здесь — не пустая карточка, а выполненная команда.

/**
 * Разложить вывод на блоки по маркерам `@@имя`.
 *
 * Строки до первого маркера отбрасываются: там живёт то, что печатает сама оболочка при входе
 * (баннер, сообщение почты) — оно не относится ни к одному блоку.
 */
export function sections(out: string): Record<string, string[]> {
  const sec: Record<string, string[]> = {}
  let cur = ''
  for (const line of out.split('\n')) {
    const m = line.match(/^@@(\w+)\s*$/)
    if (m) {
      cur = m[1]
      sec[cur] = []
    } else if (cur) {
      sec[cur].push(line)
    }
  }
  // Хвостовые пустые строки — след завершающего перевода строки, а не данные. Каждый
  // потребитель отбрасывал их сам (или забывал, и тогда пустая строка уезжала в разбор как
  // значение); отбросим здесь один раз.
  for (const key of Object.keys(sec)) {
    while (sec[key].length > 0 && sec[key][sec[key].length - 1].trim() === '') sec[key].pop()
  }
  return sec
}

/**
 * Значение в одинарных кавычках для передачи в оболочку.
 *
 * Внутри одинарных кавычек оболочка не трактует ничего, кроме самой кавычки, — поэтому
 * единственное, что нужно обработать, это она сама: закрыть строку, вставить экранированную
 * кавычку и открыть снова (`'\''`).
 */
export function quoteForShell(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}
