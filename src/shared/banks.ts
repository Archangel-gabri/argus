// Опознание счёта: к какому банку или брокеру он относится.
//
// Раньше это решалось регулярным выражением прямо в месте использования — и таких мест стало
// четыре: два в фоновом опросе, два на экране. Совпадать они обязаны точь-в-точь, иначе счёт
// получает кнопку входа, но не опрашивается (или наоборот), и понять, почему, можно только
// сличив выражения глазами.
//
// Опознаём по названию, а не по отдельному полю: владелец заводит счёт словами («Т-Банк»,
// «Сбербанк»), и требовать от него выбирать банк из списка ради того, что уже написано в
// названии, значит выдумывать работу. Неопознанное имя остаётся ручным счётом — безопасный
// исход, в отличие от попытки угадать.

export type BankId = 'tbank' | 'sber'

interface Match {
  id: BankId
  /** Что ищем в паре «организация + название». */
  test: RegExp
}

// Разделитель между «Т» и «Банк» владелец пишет как угодно — дефисом, пробелом или слитно,
// и в двух алфавитах сразу («Т-Банк», «T-Bank»). Требовать от него одного написания нельзя:
// счёт заводится словами, а не выбором из списка.
const SEP = '[-\\s]?'
const BANK_MATCHES: Match[] = [
  { id: 'tbank', test: new RegExp(`т${SEP}банк|тинькофф|t${SEP}bank|tinkoff`, 'i') },
  { id: 'sber', test: /сбер|sber/i }
]

export interface AccountLike {
  kind: string
  institution: string
  name: string
}

const haystack = (a: AccountLike): string => `${a.institution} ${a.name}`

/**
 * Банк, чей КАРТОЧНЫЙ счёт читается из сессии кабинета. null — не банк либо не поддержан.
 *
 * Брокерский счёт того же банка сюда не попадает: у него свой путь (токен API), и обращаться к
 * нему как к карточному нельзя.
 */
export function bankOf(account: AccountLike): BankId | null {
  if (account.kind !== 'bank') return null
  return BANK_MATCHES.find((m) => m.test.test(haystack(account)))?.id ?? null
}

/** Брокерский счёт Т-Инвестиций: единственный российский счёт с настоящим API. */
export function isTinvest(account: AccountLike): boolean {
  // Организация у такого счёта обычно записана как «Т-Банк» кириллицей, а название — как
  // «Т-Инвестиции»: годится любое из двух, поэтому здесь та же пара алфавитов, что и выше.
  return account.kind === 'broker' && new RegExp(`т${SEP}инвест|тинькофф|т${SEP}банк|t${SEP}bank|tinkoff`, 'i').test(haystack(account))
}
