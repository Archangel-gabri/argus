import type { AiLimits } from '../main/types'

/**
 * Слить лимиты, которые умеет редактировать форма, с теми, которых она не знает.
 *
 * Форма показывает четыре поля из десяти (`rpm`, `rpd`, `windowHours`, `windowTokens`), а в
 * хранилище объект уезжает целиком. Пока слияния не было, правка одной заметки обнуляла
 * `tpd`, `weekTokens`, `tpmo` и `rpmo` — и это было видно: полосы «Сегодня» и «7 дней»
 * переключались с точного потолка на приблизительную оценку по наблюдаемому максимуму, а
 * строка «По условиям тарифа» исчезала. Восстановить потерянное было нечем: засев дозаполняет
 * только пустые поля и только у записей из файла, а заданное руками не возвращается никак.
 *
 * `null` от формы — это осознанное «нет лимита», и он ЗАТИРАЕТ прежнее значение: иначе снять
 * однажды введённый потолок стало бы невозможно.
 *
 * `undefined` — противоположный случай: поле не разобралось (человек написал буквы). Такое
 * значение прежнее НЕ трогает. Разницу видно на живом вводе: пустое поле снимает потолок,
 * а неразобранный ввод оставляет его на месте, вместо того чтобы молча стереть.
 */
export function mergeLimits(previous: AiLimits | undefined, edited: AiLimits): AiLimits {
  const out: AiLimits = { ...(previous ?? {}) }
  for (const [key, value] of Object.entries(edited)) {
    if (value === undefined) continue
    out[key as keyof AiLimits] = value as number | null
  }
  return out
}
