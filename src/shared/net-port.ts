// Допустимость сетевого порта.
//
// Жило двумя копиями: в `main/forward.ts` и в `renderer/lib/forward-policy.ts`. Копия в
// renderer появилась не по небрежности — renderer не имеет права импортировать main, — но
// именно для такого случая и существует `shared`. Пока копий две, послабление в одной делает
// проверку в другой бессмысленной: одна сторона примет то, что вторая отвергнет, и человек
// увидит форму, которая «сохранилась», а действие не произошло.

/** Порт в допустимых пределах: целое от 1 до 65535. Ноль и 65536 — не порты. */
export const isForwardPort = (port: number): boolean =>
  Number.isInteger(port) && port >= 1 && port <= 65_535
