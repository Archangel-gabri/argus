// Приблизительные курсы валют к доллару — единственная таблица на всё приложение.
//
// Ей пользуются три места: vault.ts (стоимость серверов), data/subscriptions.ts (подписки и
// счета), lib/ai-account.ts (окупаемость ИИ-подписок). Раньше у каждого была СВОЯ копия с
// комментарием «держать одинаковыми» — и копии разошлись: TRY отличалась третьим знаком, а в
// третьей таблице не было половины валют, из-за чего окупаемость подписки в JPY показывалась
// как «не знаю», хотя месячный итог в той же валюте на экране подписок был посчитан.
// Комментарий ничего не проверяет; одну таблицу проверяют tsc (`satisfies` ниже) и тест
// src/main/fx-tables.test.ts.
//
// Курсы — снимок 2026 года, вшиты и не обновляются; это осознанно: таблица сводит смешанные
// валюты к одному порядку величины, а не ведёт бухгалтерию. При слиянии копий у TRY оставлен
// 0.03 (а не 0.029 из третьей): его уже показывали экраны серверов и подписок, и менять цифру,
// которую владелец видел, ради третьего знака статичного курса незачем.
import type { Currency } from '../main/types'

// `satisfies` требует курс для КАЖДОЙ валюты из CURRENCY_CODES и запрещает лишние: валюта,
// добавленная в список без курса, упадёт ещё на tsc, не дожидаясь теста. Импорт выше — только
// тип: кода из main он в renderer-бандл не тянет.
export const FX_TO_USD: Record<string, number> = {
  USD: 1, EUR: 1.08, RUB: 0.0126, GBP: 1.27, CNY: 0.14, JPY: 0.0067, CHF: 1.11,
  CAD: 0.73, AUD: 0.66, INR: 0.012, BRL: 0.2, KRW: 0.00075, TRY: 0.03, PLN: 0.25,
  UAH: 0.025, KZT: 0.0021, AED: 0.27, SEK: 0.095, NOK: 0.093, SGD: 0.74,
  PKR: 0.0036
} satisfies Record<Currency, number>

/** Курс здесь справочный: он вшит в приложение и не обновляется. Цифры на нём — приблизительные. */
export const FX_IS_APPROXIMATE = true

/**
 * Сумма в долларах. Неизвестная валюта — null: соврать курсом хуже, чем не показать.
 *
 * Именно null, а не «курс 1»: `?? 1` уже превращал «100 BTC» в «$100» в общем итоге
 * (см. src/main/device-cost.test.ts) — цифра выглядела правдоподобно и была неправдой.
 * «Не знаю» обязано быть отличимым от знания, а что с ним делать — решает вызывающий:
 * показать прочерк, не показать ничего, но не выдумать курс.
 */
export function toUsd(amount: number, currency: string): number | null {
  const rate = FX_TO_USD[currency]
  return rate == null ? null : amount * rate
}
