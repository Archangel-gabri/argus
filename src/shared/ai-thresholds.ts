// Пороги внимания для ИИ-доступов — одни на сторожа (main) и экран (renderer).
//
// Обе стороны судят об одном и том же: сторож шлёт уведомление, экран собирает список «требует
// внимания». Пока пороги были объявлены в двух файлах, их равенство держалось на комментарии
// «тот же порог, что у сторожа» — то есть на честном слове. Разъехавшиеся пороги коварны тем,
// что обе цифры выглядят осмысленно: уведомление уже горит, а экран ещё говорит «всё в порядке».
//
// Вынесены в константы не ради красоты, а чтобы их было видно и можно было обсуждать.
export const CREDIT_WARNING_USD = 5 // остаток, ниже которого пора пополняться
export const CREDIT_CRITICAL_USD = 1 // остаток, при котором работа встанет со дня на день
export const KEY_EXPIRY_WARNING_DAYS = 14 // за сколько дней предупреждать об истечении ключа
