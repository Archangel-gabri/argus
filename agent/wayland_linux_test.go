// Уменьшение под возможности программного кодировщика. Главное требование — НЕ ИСКАЖАТЬ:
// именно принудительные 1920×1080 превращали сверхширокий экран 21:9 в 16:9.
func TestFitAspect(t *testing.T) {
	cases := []struct {
		inW, inH   int
		maxH       int
		outW, outH int
		reason     string
	}{
		{3440, 1440, 1080, 2580, 1080, "21:9 остаётся 21:9 (3440/1440 = 2580/1080)"},
		{1920, 1080, 1080, 1920, 1080, "ровно на границе — не трогаем"},
		{1366, 768, 1080, 1366, 768, "ниже предела — оставляем как есть"},
		{3840, 2160, 1080, 1920, 1080, "4K уменьшается ровно вдвое"},
		{2560, 1600, 1080, 1728, 1080, "16:10 (1728/1080 = 1.6) — пропорция сохранена"},
		{3440, 1440, 0, 3440, 1440, "предела нет — родное разрешение"},
		{1365, 767, 0, 1364, 766, "без предела всё равно приводим к чётным"},
	}
	for _, c := range cases {
		w, h := fitAspect(c.inW, c.inH, c.maxH)
		if w != c.outW || h != c.outH {
			t.Errorf("fitAspect(%d, %d, %d) = %d×%d, ожидалось %d×%d (%s)",
				c.inW, c.inH, c.maxH, w, h, c.outW, c.outH, c.reason)
		}
		if w%2 != 0 || h%2 != 0 {
			t.Errorf("fitAspect(%d, %d, %d) вернул нечётную сторону %d×%d", c.inW, c.inH, c.maxH, w, h)
		}
	}
}

// Цепочки кодировщиков — это половина конвейера, и в них легко потерять то, что было куплено
// отладкой. Вторая половина (источник, очередь, хвост) живёт в помощнике, и он вшит в бинарь,
// поэтому проверяется здесь же — как текст.
func TestWaylandChains(t *testing.T) {
	if len(waylandEncoders) < 2 {
		t.Fatal("каскад кодировщиков пуст — трансляция на Wayland не поедет")
	}

	for _, e := range waylandEncoders {
		// Помощник находит кодировщик по имени, чтобы менять битрейт на живом конвейере.
		// Без имени управление качеством молча перестанет работать.
		if !strings.Contains(e.chain(60), "name=enc") {
			t.Errorf("цепочка %q без name=enc — помощник не найдёт кодировщик", e.name)
		}
		// videorate в этом конвейере запрещён по результатам ТРЁХ живых проверок: он придерживает
		// кадр, чтобы посчитать темп по двум соседним, и на источнике, отдающем кадры по
		// изменениям картинки, это давало 1 кадр за 10 секунд — в том числе уже ПОСЛЕ включения
		// keepalive. Частота ограничивается сбросом кадров в помощнике.
		if strings.Contains(e.chain(60), "videorate") {
			t.Errorf("цепочка %q тянет videorate — проверено трижды, он даёт 1 кадр за 10с", e.name)
		}
	}

	// Первый (основной) аппаратный путь не должен преобразовывать формат на процессоре:
	// NVENC принимает BGRx напрямую и делает преобразование одним CUDA-ядром внутри себя.
	if strings.Contains(waylandEncoders[0].chain(60), "videoconvert") ||
		strings.Contains(waylandEncoders[0].chain(60), "cudaupload") {
		t.Error("в основном аппаратном пути появилось преобразование формата — оно втрое дороже")
	}
	if !strings.Contains(waylandEncoders[0].chain(60), "repeat-sequence-header=true") {
		t.Error("у nvh264enc выключен repeat-sequence-header (по умолчанию false) — " +
			"клиент, подключившийся между ключевыми кадрами, не настроит декодер")
	}

	// Битрейт обязателен в КАЖДОЙ цепочке: без него кодировщик берёт его «автоматически»
	// и на анимации во весь экран выдал 60 Мбит/с вместо 8. Потеря этой настройки при
	// переносе конвейера в помощника стоила отдельного замера, чтобы её заметить.
	for _, e := range waylandEncoders {
		if !strings.Contains(e.chain(60), "bitrate=") {
			t.Errorf("в цепочке %q нет битрейта — кодировщик выберет его сам, и канал не выдержит", e.name)
		}
	}

	// Программный путь обязан уменьшать картинку: родное 3440×1440 ему не по силам.
	sw := waylandEncoders[len(waylandEncoders)-1]
	if sw.scaleTo <= 0 {
		t.Error("у программного пути нет предела по высоте — он не потянет родное разрешение")
	}
}

// Помощник вшит в бинарь, поэтому его текст — часть поставки, и инварианты конвейера
// проверяются вместе с ним.
func TestEmbeddedHelper(t *testing.T) {
	s := string(portalStreamScript)

	// keepalive-time обязателен: KWin объявляет переменную частоту и отдаёт кадр только при
	// изменениях картинки, а KPipeWire выбрасывает дубликаты. Без него поток на спокойном
	// экране замолкает, и исправный конвейер выглядит сломанным.
	if !strings.Contains(s, "keepalive-time=120") {
		t.Error("в помощнике нет keepalive-time — поток замолчит на неподвижном экране")
	}
	// SPS/PPS перед каждым ключевым кадром — требование WebCodecs в режиме annexb.
	if !strings.Contains(s, "config-interval=-1") {
		t.Error("в помощнике нет config-interval=-1")
	}
	// Двоичный поток идёт в fd 1 и ничего кроме него: журнал в том же канале попал бы прямо
	// в видео.
	if !strings.Contains(s, "fdsink fd=1") {
		t.Error("в помощнике нет вывода в fd 1")
	}
	// Ищем именно ЗВЕНО конвейера, а не упоминание: в помощнике есть комментарий о том,
	// почему videorate здесь не годится, и его текст трогать не надо.
	if strings.Contains(s, "! videorate") {
		t.Error("в помощнике появилось звено videorate — он несовместим с этим источником")
	}
	// Ограничение частоты — сбросом кадров, а не удержанием.
	if !strings.Contains(s, "PadProbeReturn.DROP") {
		t.Error("в помощнике нет сброса кадров — ограничить частоту будет нечем")
	}
}

// Разбор событий помощника: размеры приходят ДО первого кадра, и именно они — правда.
func TestParseHelperEvent(t *testing.T) {
	ev, ok := parseHelperEvent(`{"ev":"stream","node":58,"width":3440,"height":1440,"reused":true}`)
	if !ok || ev.Ev != "stream" || ev.Width != 3440 || ev.Height != 1440 || !ev.Reused {
		t.Errorf("событие потока разобрано неверно: %+v (ok=%v)", ev, ok)
	}

	if ev, ok := parseHelperEvent(`{"ev":"error","error":"конвейер не собрался"}`); !ok || ev.Error == "" {
		t.Errorf("событие ошибки разобрано неверно: %+v (ok=%v)", ev, ok)
	}

	// Обычные строки ffmpeg и мусор не должны притворяться событиями.
	for _, line := range []string{
		"[VAAPI @ 0x55] Failed to initialise VAAPI connection: -1",
		"",
		"{}",
		`{"width":100}`,
		"не JSON вовсе",
	} {
		if _, ok := parseHelperEvent(line); ok {
			t.Errorf("строка %q принята за событие помощника", line)
		}
	}
}
