//go:build linux

package main

import (
	"os/exec"
	"time"
)

// Проверка варианта захвата требует, чтобы на экране ЧТО-ТО поменялось.
//
// На Wayland портал отдаёт кадры только при изменениях картинки: спокойный рабочий стол
// не производит ни одного кадра сколько бы мы ни ждали. А критерий у нас один и правильный —
// пришедшие кадры, потому что кодировщик умеет «создаться» и молчать. Без изменения на экране
// эти два состояния неразличимы, и исправный путь отвергается вместе со сломанным.
//
// Изменение делаем самым безобидным из возможных — коротким уведомлением на самой машине.
// Мышь и клавиатуру не трогаем: это чужой рабочий стол, и дёргать курсор ради проверки нельзя.
// Побочная польза важнее самой проверки: тот, кто сидит за машиной, ВИДИТ, что к экрану
// подключились. Для удалённого доступа это правильное поведение, а не утечка.
func nudgeScreen() {
	if _, err := exec.LookPath("notify-send"); err != nil {
		return
	}
	cmd := exec.Command("notify-send", "--app-name=Argus", "--expire-time=4000",
		"--icon=video-display", "Argus", "Подключение к экрану")
	ensureSessionEnv(cmd)
	_ = cmd.Run()
}

// nudgeSoon шевелит экран сразу и ещё раз чуть позже: первое уведомление может уйти раньше,
// чем конвейер дошёл до состояния PLAYING, и тогда кадр с ним просто не совпадёт по времени.
func nudgeSoon(stop <-chan struct{}) {
	go func() {
		nudgeScreen()
		select {
		case <-stop:
		case <-time.After(2 * time.Second):
			nudgeScreen()
		}
	}()
}
