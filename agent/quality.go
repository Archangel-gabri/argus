package main

import (
	"sync"
	"time"
)

// Ступени качества и правило перехода между ними.
//
// Решение принимает СЕРВЕР, а не клиент, по двум причинам: только он видит собственную очередь
// отправки и только он может тронуть кодировщик. Клиент присылает наблюдения — сколько кадров
// он получил и насколько отстаёт его декодер.
//
// Логика вынесена сюда отдельно и без единого обращения к сети именно ради проверок: правило
// «когда сбавить, когда прибавить» ошибается тихо, и поймать это на живом стенде дорого.

// qualityTier — одна ступень: сколько кадров в секунду и какой битрейт.
// fps = 0 означает «не ограничивать»: отдаём столько, сколько даёт композитор.
type qualityTier struct {
	fps     int
	kbps    int
	comment string
}

// Лестница сверху вниз. Верхняя ступень — то, что мы делаем сейчас без подстройки: не
// ограничивать частоту и держать заданный битрейт. Нижняя рассчитана на канал через релей,
// где важнее плавность, чем чёткость.
var qualityLadder = []qualityTier{
	{fps: 0, kbps: 8000, comment: "как есть"},
	{fps: 60, kbps: 8000, comment: "60 к/с"},
	{fps: 30, kbps: 4000, comment: "30 к/с"},
	{fps: 15, kbps: 2000, comment: "15 к/с, экономия канала"},
}

// clientStats — наблюдения клиента за окно времени.
type clientStats struct {
	// RxFrames — сколько кадров клиент ПОЛУЧИЛ за окно.
	RxFrames int `json:"rxFrames"`
	// DecodeQueue — сколько кадров ждёт в очереди декодера. Растёт, когда клиент не успевает.
	DecodeQueue int `json:"decodeQueue"`
	// Lost — сколько кадров не доехало: клиент видит разрывы в нумерации. Это прямое
	// измерение потерь, не зависящее от того, что насчитал сервер.
	Lost int `json:"lost"`
	// WindowMs — длина окна наблюдения.
	WindowMs int `json:"windowMs"`
}

// qualityGovernor — состояние подстройки для одного сеанса.
type qualityGovernor struct {
	mu        sync.Mutex
	tier      int
	calmSince time.Time
	// sent — сколько кадров сервер отправил за текущее окно; сбрасывается при каждом решении.
	sent int
}

const (
	// Очередь декодера, выше которой клиент считается не успевающим. Один-два кадра в очереди
	// нормальны и означают лишь конвейеризацию; четыре — это уже накопление.
	queueTooDeep = 3
	// Доля дошедших кадров, ниже которой канал считается узким: сервер отправил, клиент не
	// получил — значит теряется по дороге или не читается вовремя.
	deliveredTooLow = 0.75
	// Сколько кадров за окно можно потерять, не считая это узким каналом.
	lostTooMany = 3
	// Сколько времени должно быть спокойно, прежде чем поднимать качество обратно. Прибавлять
	// надо неохотно: качели между ступенями заметнее, чем сама пониженная ступень.
	calmBeforeRaise = 8 * time.Second
)

// decide возвращает новую ступень и признак «ступень изменилась».
//
// Правило намеренно несимметрично: вниз — сразу по первому же признаку, вверх — только после
// продолжительного спокойствия. Пользователь замечает заикание мгновенно, а возврат чёткости
// на несколько секунд позже не замечает вовсе.
func (g *qualityGovernor) decide(st clientStats, now time.Time) (qualityTier, bool) {
	g.mu.Lock()
	defer g.mu.Unlock()

	delivered := 1.0
	if g.sent > 0 {
		delivered = float64(st.RxFrames) / float64(g.sent)
	}
	// Потери в сети — сигнал не менее веский, чем отставание декодера: одиночный пропуск
	// бывает и в норме, но несколько за окно означают, что канал не тянет.
	struggling := st.DecodeQueue > queueTooDeep || delivered < deliveredTooLow || st.Lost > lostTooMany

	old := g.tier
	switch {
	case struggling && g.tier < len(qualityLadder)-1:
		g.tier++
		g.calmSince = time.Time{}
	case struggling:
		// Уже на нижней ступени — ниже некуда, но и «спокойно» это не считается.
		g.calmSince = time.Time{}
	default:
		if g.calmSince.IsZero() {
			g.calmSince = now
		} else if g.tier > 0 && now.Sub(g.calmSince) >= calmBeforeRaise {
			g.tier--
			g.calmSince = now
		}
	}
	g.sent = 0
	return qualityLadder[g.tier], g.tier != old
}

// note учитывает отправленный кадр — знаменатель для доли дошедших.
func (g *qualityGovernor) note() {
	g.mu.Lock()
	g.sent++
	g.mu.Unlock()
}
